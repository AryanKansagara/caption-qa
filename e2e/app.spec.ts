test('review: edit a cue, reject bad times, keep it after a reload, revert to as delivered', async ({ page }) => {
  await newProject(page)
  await importFiles(page, ['a_en.srt', srt([1000, 3000, 'First cue'], [4000, 6000, 'Second cue'])])
  await tab(page, 'Review')
  await page.locator('table.sbs tbody tr').nth(1).click()
  const ed = page.locator('.editor')
  await expect(ed.getByRole('heading', { name: 'Cue #2' })).toBeVisible()
  await ed.getByLabel('Out').fill('00:00:03.000')
  await expect(ed.getByRole('button', { name: 'Save' })).toBeDisabled()
  await ed.getByLabel('Out').fill('00:00:06.500')
  await ed.locator('textarea').fill('Edited cue')
  await ed.getByRole('button', { name: 'Save' }).click()
  await expect(toasts(page)).toContainText('Saved cue #2')
  await page.reload()
  await page.locator('table.sbs tbody tr').nth(1).click()
  await expect(ed.locator('textarea')).toHaveValue('Edited cue')
  await ed.getByRole('button', { name: 'As delivered' }).click()
  await ed.getByRole('button', { name: 'Save' }).click()
  await expect(page.locator('table.sbs tbody tr').nth(1)).toContainText('Second cue')
  await expect(ed.getByRole('button', { name: 'As delivered' })).toHaveCount(0)
})

