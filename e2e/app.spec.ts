test('report, CSVs, project JSON and copy', async ({ page }) => {
  await newProject(page)
  await importFiles(page, ['a_en.srt', srt([1000, 3500, 'One, "fine" day'], [3000, 5000, '<img src=x onerror=alert(1)>Two'])])
  await tab(page, 'Export')
  await page.getByRole('row').filter({ hasText: 'a_en.srt' }).getByRole('button', { name: 'Copy' }).click()
  await expect.poll(() => copied(page)).toContain('00:00:01,000 --> 00:00:03,500\nOne, "fine" day\n')
  const csv = await downloaded(page, () => page.getByRole('button', { name: 'Issues CSV' }).click())
  expect(csv.text.split('\n')[1]).toBe('en,source,a_en.srt,2,00:00:03.000,00:00:05.000,overlap,error,Starts 500 ms before the previous cue ends.,Two')
  const sum = await downloaded(page, () => page.getByRole('button', { name: 'Summary CSV' }).click())
  expect(sum.text.split('\n')[0]).toMatch(/^language,role,file,cues,score,cps,wpm,/)
  const json = await downloaded(page, () => page.getByRole('button', { name: 'Download project JSON' }).click())
  expect(JSON.parse(json.text).tracks[0].cues).toHaveLength(2)
  await page.getByRole('link', { name: 'Open printable report' }).click()
  await expect(page.getByRole('heading', { name: 'Pass / fail per rule' })).toBeVisible()
  await expect(page.locator('.report-table').first().locator('tbody tr')).toContainText('Fail')
  expect(await page.locator('.report img').count()).toBe(0)
})

test('rule profile: preset, children, custom values and reset persist', async ({ page }) => {
  await newProject(page)
  // 36 characters in 2 s is 18 CPS: fine for English adults (20), too fast for children (17).
  await importFiles(page, ['a_en.srt', srt([1000, 3000, 'Thirty six characters, count them ok'])])
  await tab(page, 'QC overview')
  expect(await issues(page)).toEqual([])
  await tab(page, 'Setup')
  await page.getByText('Children’s programme reading speeds').click()
  await tab(page, 'QC overview')
  expect(await issues(page)).toEqual(['#1 warn Reading speed (CPS): 18.0 CPS over the 17 CPS limit (36 chars in 2.00 s).'])
  await tab(page, 'Setup')
  await page.getByLabel('Max characters / line').fill('30')
  await page.reload()
  await expect(page.getByLabel('Max characters / line')).toHaveValue('30')
  await expect(page.getByText('with custom edits')).toBeVisible()
  await tab(page, 'QC overview')
  expect(await issues(page)).toContain('#1 error Line length: Line 1 has 36 characters (max 30).')
  await tab(page, 'Setup')
  await page.getByRole('button', { name: 'Reset to preset' }).click()
  await expect(page.getByLabel('Max characters / line')).toHaveValue('42')
})

